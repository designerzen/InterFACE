import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { createServer } from 'node:http'
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const pug = require('pug')
const sass = require('sass')
const css = sass.compile('source/index.scss', { logger: sass.Logger.silent }).css
const markup = pug.renderFile('source/partials/a11y.pug')
const moduleSource = readFileSync('source/accessibility/accessibility-panel.js', 'utf8')
const server = createServer((request, response) => {
	if (request.url === '/source/assets/icons/close-24px.svg') {
		response.setHeader('Content-Type', 'image/svg+xml')
		response.end(readFileSync('source/assets/icons/close-24px.svg'))
	} else if (request.url === '/accessibility.js') {
		response.setHeader('Content-Type', 'text/javascript')
		response.end(moduleSource)
	} else if (request.url === '/preferences.js') {
		response.setHeader('Content-Type', 'text/javascript')
		response.end(readFileSync('source/accessibility/preferences.js', 'utf8'))
	} else {
		response.end(`<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>${css}</style></head><body>${markup}<main id="app"><h1>PhotoSYNTH</h1><button style="position:fixed;left:0;bottom:0" id="button-accessibility" aria-controls="accessibility-panel" aria-expanded="false" hidden>Accessibility settings</button><button>Play music</button><a href="#app">Help</a></main><script type="module">import {setupAccessibilityControls} from '/accessibility.js'; window.controls = setupAccessibilityControls(); window.setup = setupAccessibilityControls;</script></body></html>`)
	}
})
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
const browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_CHANNEL || 'msedge' })
try {
	const context = await browser.newContext({ viewport: { width: 1280, height: 900 } })
	const page = await context.newPage()
	await page.goto(`http://127.0.0.1:${server.address().port}`)
	await page.waitForFunction(() => window.controls)
	const errors = []
	page.on('pageerror', error => errors.push(error.message))
	assert.equal(await page.evaluate(() => window.controls === window.setup()), true)
	await page.locator('#accessibility-tab').click()
	assert.equal(await page.locator('#accessibility-panel').evaluate(el => el.matches(':modal')), true)
	await page.locator('.a11y-close').focus()
	await page.keyboard.press('Shift+Tab')
	assert.equal(await page.locator('[data-close-accessibility]').last().evaluate(el => el === document.activeElement), true)
	await page.keyboard.press('Tab')
	assert.equal(await page.locator('.a11y-close').evaluate(el => el === document.activeElement), true)
	// Opening the modal makes the instrument inert; keystrokes never reach shortcuts.
	await page.evaluate(() => { window.shortcutCalls = 0; for (const type of ['keydown', 'keyup']) window.addEventListener(type, () => window.shortcutCalls++) })
	await page.locator('#a11y-theme').focus()
	await page.keyboard.press('a')
	assert.equal(await page.evaluate(() => window.shortcutCalls), 0)
	for (const theme of ['light', 'dark', 'contrast-dark', 'contrast-light', 'sepia', 'ocean', 'monochrome', 'system', 'original']) {
		await page.selectOption('#a11y-theme', theme)
		assert.equal(await page.locator('#a11y-theme').inputValue(), theme)
	}
	await page.selectOption('#a11y-theme', 'light')
	await page.selectOption('#a11y-text-size', '200')
	await page.locator('[data-preference="readableFont"]').check()
	await page.reload()
	await page.waitForFunction(() => window.controls)
	assert.equal(await page.locator('#a11y-theme').inputValue(), 'light')
	assert.equal(await page.locator('[data-preference="readableFont"]').isChecked(), true)
	assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).fontSize), '32px')
	await page.evaluate(() => window.controls.show())
	await page.locator('#a11y-theme').focus()
	await page.keyboard.press('Escape')
	assert.equal(await page.locator('#accessibility-panel').isVisible(), false)
	assert.equal(await page.locator('#accessibility-tab').evaluate(el => el === document.activeElement), true)
	await page.locator('#accessibility-tab').click()
	await page.selectOption('#a11y-motion', 'reduce')
	assert.equal(await page.evaluate(() => document.documentElement.classList.contains('a11y-reduce-motion')), true)
	await page.locator('[data-reset-accessibility]').click()
	assert.equal(await page.locator('#a11y-text-size').inputValue(), '100')
	await page.locator('summary').filter({ hasText: 'Focus, borders and links' }).click()
	await page.selectOption('#a11y-borderSize', '4px')
	await page.selectOption('#a11y-cornerRadius', '1rem')
	assert.equal(await page.locator('.a11y-close').evaluate(el => getComputedStyle(el).borderTopWidth), '4px')
	assert.equal(await page.locator('.a11y-close').evaluate(el => getComputedStyle(el).borderTopLeftRadius), '16px')
	await page.selectOption('#a11y-preset', 'quick-1')
	assert.equal(await page.locator('#a11y-theme').inputValue(), 'contrast-dark')
	await page.locator('summary').filter({ hasText: 'Custom colours' }).click()
	await page.locator('#a11y-pageText').fill('#000000')
	assert.equal(await page.locator('#a11y-theme').inputValue(), 'custom')
	assert.match(await page.locator('#a11y-contrast').textContent(), /Page text: 1.00:1 \(below 4.5:1\)/)
	await page.locator('#a11y-pageText').fill('#ffffff')
	assert.match(await page.locator('#a11y-contrast').textContent(), /Page text: 21.00:1 \(meets 4.5:1\)/)
	await page.locator('summary').filter({ hasText: 'Font and spacing options' }).click()
	await page.selectOption('#a11y-fontFamily', 'Verdana')
	await page.selectOption('#a11y-lineSpacing', '2')
	assert.match(await page.locator('#a11y-theme').evaluate(el => getComputedStyle(el).fontFamily), /Verdana/)
	assert.equal(await page.locator('#a11y-theme').evaluate(el => parseFloat(getComputedStyle(el).lineHeight) / parseFloat(getComputedStyle(el).fontSize)), 2)
	await page.locator('summary').filter({ hasText: 'Save and transfer' }).click()
	await page.locator('#a11y-preset-name').fill('My reading settings')
	await page.locator('[data-save-preset]').click()
	assert.equal(await page.locator('#a11y-preset').inputValue(), 'saved-0')
	const downloadReady = page.waitForEvent('download')
	await page.locator('[data-export-accessibility]').click()
	const download = await downloadReady
	const exported = JSON.parse(readFileSync(await download.path(), 'utf8'))
	assert.equal(exported.preferences.fontFamily, 'Verdana')
	assert.equal(exported.presets[0].name, 'My reading settings')
	await page.locator('[data-reset-accessibility]').click()
	await page.locator('#a11y-import').setInputFiles({ name: 'preferences.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(exported)) })
	await page.waitForFunction(() => document.documentElement.dataset.a11yTheme === 'custom')
	assert.equal(await page.locator('#a11y-fontFamily').inputValue(), 'Verdana')
	await page.locator('#a11y-import').setInputFiles({ name: 'unsafe.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ ...exported, preferences: { ...exported.preferences, pageText: 'url(https://invalid.example)' } })) })
	await page.waitForFunction(() => document.querySelector('[role="status"]').textContent.includes('Could not import'))
	assert.equal(await page.locator('#a11y-pageText').inputValue(), '#ffffff')
	const other = await page.context().newPage()
	await other.goto(`http://127.0.0.1:${server.address().port}`)
	await other.waitForFunction(() => window.controls)
	await other.evaluate(() => { window.controls.show(); const select = document.getElementById('a11y-theme'); select.value = 'ocean'; select.dispatchEvent(new Event('change', { bubbles: true })) })
	await page.waitForFunction(() => document.documentElement.dataset.a11yTheme === 'ocean')
	await other.close()
	await page.selectOption('#a11y-preset', 'saved-0')
	await page.locator('[data-delete-preset]').click()
	assert.equal(await page.locator('#a11y-preset option[value="saved-0"]').count(), 0)
	await page.locator('[data-reset-accessibility]').click()
	await page.emulateMedia({ reducedMotion: 'reduce', colorScheme: 'dark' })
	await page.selectOption('#a11y-theme', 'system')
	assert.equal(await page.evaluate(() => document.documentElement.dataset.a11yTheme), 'dark')
	await page.waitForFunction(() => document.documentElement.classList.contains('a11y-reduce-motion'))
	await page.setViewportSize({ width: 375, height: 667 })
	await page.selectOption('#a11y-text-size', '200')
	await page.locator('[data-preference="textSpacing"]').check()
	await page.locator('[data-preference="largeTargets"]').check()
	const box = await page.locator('#accessibility-panel').boundingBox()
	assert.ok(box.x >= 0 && box.x + box.width <= 375 && box.y >= 0 && box.y + box.height <= 667, JSON.stringify(box))
	await page.screenshot({ path: `${process.env.TEMP || '/tmp'}/photosynth-a11y-mobile-debug.png` })
	const overflow = await page.locator('#accessibility-panel').evaluate(el => [...el.querySelectorAll('*')].filter(child => child.getBoundingClientRect().right > el.getBoundingClientRect().right).map(child => [child.tagName, child.id, child.className, child.getBoundingClientRect().width, getComputedStyle(child).minWidth]))
	assert.equal(await page.locator('#accessibility-panel').evaluate(el => el.scrollWidth <= el.clientWidth + 1), true, JSON.stringify(overflow))
	await page.setViewportSize({ width: 320, height: 568 })
	const narrowOverflow = await page.locator('#accessibility-panel').evaluate(el => [...el.querySelectorAll('*')].filter(child => child.getBoundingClientRect().right > el.getBoundingClientRect().right).map(child => [child.tagName, child.id, child.className, child.getBoundingClientRect().width]))
	assert.equal(await page.locator('#accessibility-panel').evaluate(el => el.scrollWidth <= el.clientWidth + 1), true, JSON.stringify(narrowOverflow))
	await page.locator('[data-close-accessibility]').last().scrollIntoViewIfNeeded()
	assert.equal(await page.locator('[data-close-accessibility]').last().isVisible(), true)
	assert.equal(await page.locator('[data-reset-accessibility]').evaluate(el => el.scrollHeight <= el.clientHeight + 1), true)
	await page.screenshot({ path: `${process.env.TEMP || '/tmp'}/photosynth-a11y-mobile.png` })
	await page.evaluate(() => localStorage.setItem('photosynth.accessibility.v1', '{'))
	await page.reload()
	await page.waitForFunction(() => window.controls)
	assert.equal(await page.locator('#a11y-theme').inputValue(), 'original')
	await page.evaluate(() => { Storage.prototype.setItem = () => { throw new Error('blocked') }; window.controls.show() })
	await page.selectOption('#a11y-theme', 'sepia')
	assert.match(await page.locator('[role="status"]').textContent(), /could not save/)
	assert.equal(await page.evaluate(() => document.documentElement.dataset.a11yTheme), 'sepia')
	// The top tab is available during onboarding, then hands off to shared settings.
	await page.emulateMedia({ reducedMotion: 'no-preference' })
	await page.setViewportSize({ width: 1280, height: 900 })
	await page.locator('.a11y-close').click()
	assert.equal(await page.locator('#accessibility-tab').isVisible(), true)
	assert.equal((await page.locator('#accessibility-tab').boundingBox()).y, 0)
	assert.equal(await page.locator('#button-accessibility').isVisible(), false)
	await page.locator('#accessibility-tab').click()
	await page.locator('#a11y-theme').focus()
	await page.evaluate(() => document.documentElement.classList.add('loaded'))
	await page.waitForFunction(() => document.getElementById('accessibility-tab').hidden)
	assert.equal(await page.locator('#accessibility-panel').isVisible(), false)
	assert.equal(await page.locator('#button-accessibility').isVisible(), true)
	assert.equal(await page.locator('#button-accessibility').evaluate(el => el === document.activeElement), true)
	await page.locator('#button-accessibility').click()
	assert.equal(await page.locator('#accessibility-panel').isVisible(), true)
	assert.equal(await page.locator('#a11y-title').isVisible(), true)
	assert.equal(await page.locator('#button-accessibility').getAttribute('aria-expanded'), 'true')
	assert.equal(await page.locator('#a11y-theme').inputValue(), 'sepia')
	await page.keyboard.press('Escape')
	assert.equal(await page.locator('#button-accessibility').getAttribute('aria-expanded'), 'false')
	assert.equal(await page.locator('#button-accessibility').evaluate(el => el === document.activeElement), true)
	await page.locator('#button-accessibility').click()
	await page.locator('.a11y-close').click()
	assert.equal(await page.locator('#accessibility-panel').isVisible(), false)
	await page.evaluate(() => document.documentElement.classList.add('player-selection'))
	await page.waitForFunction(() => !document.getElementById('accessibility-tab').hidden)
	assert.equal(await page.locator('#button-accessibility').isVisible(), false)
	await page.locator('#accessibility-tab').click()
	assert.equal(await page.locator('#a11y-title').isVisible(), true)
	await page.screenshot({ path: `${process.env.TEMP || '/tmp'}/photosynth-a11y-top.png` })
	await page.emulateMedia({ forcedColors: 'active' })
	await page.locator('.a11y-close').focus()
	assert.notEqual(await page.locator('.a11y-close').evaluate(el => getComputedStyle(el).outlineStyle), 'none')
	assert.deepEqual(errors, [])
	console.log('Accessibility browser checks passed: modal focus, keyboard isolation, themes, typography, contrast feedback, presets, export/import validation, cross-tab sync, persistence, reset, system preferences, forced colours, mobile at 200% with spacing, blocked storage and entry-point handoff.')
} finally {
	await browser.close()
	server.close()
}





