import pug from 'pug'
import { setupEngineInterface } from '../source/dom/ui.engine.js'
import VoiceEngineHost from '../source/audio/voice-engine-host.js'
import { createVoiceBackend } from '../source/audio/voice-engines.js'

test('engine page shows only active settings and saves edits before refreshing controls', async () => {
	document.body.innerHTML = pug.renderFile('source/partials/control-panel.pug')
	const host = new VoiceEngineHost({}, {createBackend:async () => ({configure:async () => {}, destroy:async () => {}})})
	await host.ensure()
	const saved = jest.fn()
	const ui = setupEngineInterface({getHost:() => host,getEngine:() => 'native',onChanged:saved})
	const mutations = new MutationObserver(()=>{})
	mutations.observe(document.getElementById('engine-settings'),{attributes:true,childList:true,subtree:true,characterData:true})
	ui.refresh(); ui.refresh()
	expect(mutations.takeRecords()).toHaveLength(0)
	mutations.disconnect()
	expect(document.querySelector('[data-engine-settings="native"]').hidden).toBe(false)
	expect(document.querySelector('[data-engine-settings="fm"]').disabled).toBe(true)
	document.getElementById('engine-reverb-mode').focus()
	await ui.change({reverbMode:'custom',reverbMix:0.42})
	expect(document.activeElement).toBe(document.getElementById('engine-reverb-mode'))
	expect(document.getElementById('engine-reverb-custom').hidden).toBe(false)
	expect(document.getElementById('engine-reverb-mix').value).toBe('0.42')
	expect(saved).toHaveBeenCalled()
	const shortcut = jest.fn()
	window.addEventListener('keydown',shortcut)
	document.getElementById('engine-reverb-mix').dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowRight',bubbles:true}))
	expect(shortcut).not.toHaveBeenCalled()
	window.removeEventListener('keydown',shortcut)
	await host.select('fm'); ui.refresh()
	expect(document.querySelector('[data-engine-settings="native"]').hidden).toBe(true)
	expect(document.querySelector('[data-engine-settings="fm"]').hidden).toBe(false)
	expect(document.getElementById('engine-app-reverb').hidden).toBe(false)
	const instrument = document.getElementById('engine-reverb-instrument')
	const enabled = document.getElementById('engine-reverb-instrument-enabled')
	expect(instrument.options).toHaveLength(128)
	enabled.click()
	await new Promise(resolve => setTimeout(resolve,0))
	expect(host.settings.fm.reverbDisabledPrograms).toEqual([0])
	instrument.value = '48'; instrument.dispatchEvent(new Event('change',{bubbles:true}))
	expect(document.getElementById('control-panel-engine').classList.contains('open')).toBe(true)
	expect(enabled.checked).toBe(true)
	instrument.value = '0'; instrument.dispatchEvent(new Event('change',{bubbles:true}))
	expect(enabled.checked).toBe(false)
	await ui.change({pitchBendRange:12})
	await host.select('native'); ui.refresh()
	expect(document.getElementById('engine-reverb-mix').value).toBe('0.42')
	expect(host.settings.fm.pitchBendRange).toBe(12)
	expect(enabled.checked).toBe(true)
	await host.select('yoshimi'); ui.refresh()
	expect(document.getElementById('engine-app-reverb').hidden).toBe(false)
	expect(document.getElementById('engine-reverb-instruments').hidden).toBe(true)
	expect(host.settings.yoshimi.reverbMix).toBe(0.05)
	const gain = document.getElementById('engine-output-gain')
	expect(gain.value).toBe('0')
	expect(gain.parentElement.querySelector('output').value).toBe('+0 dB')
	gain.value = '12'
	gain.dispatchEvent(new Event('change',{bubbles:true}))
	await new Promise(resolve => setTimeout(resolve,0))
	expect(host.settings.yoshimi.outputGainDb).toBe(12)
	expect(gain.parentElement.querySelector('output').value).toBe('+12 dB')
	await host.select('wam2'); ui.refresh()
	await ui.change({outputGainDb:-4.5})
	expect(gain.parentElement.querySelector('output').value).toBe('-4.5 dB')
	await host.select('yoshimi'); ui.refresh()
	expect(gain.value).toBe('12')
	await host.select('wam2'); ui.refresh()
	expect(gain.value).toBe('-4.5')
	expect(document.getElementById('engine-app-reverb').hidden).toBe(false)
	expect(document.getElementById('engine-reverb-instruments').hidden).toBe(false)
	const folder=document.getElementById('control-panel-engine')
	const launcher=folder.querySelector('.folder-link')
	launcher.focus(); launcher.click()
	folder.querySelector('.folder-return').click()
	expect(folder.contains(document.activeElement)).toBe(false)
	launcher.click()
	expect(folder.classList.contains('open')).toBe(true)
	expect(folder.classList.contains('engine-dismissed')).toBe(false)
})

test('Native settings reach its SoundFont voices and survive subsequent program loads', async () => {
	const soundfont = {setEngineReverb:jest.fn()}
	const synth = {}
	const voice = {registeredInstruments:new Map([['soundfont',soundfont],['synth',synth]]),loaded:Promise.resolve(),output:{connect(){}},loadPreset:jest.fn(async () => {})}
	const backend = await createVoiceBackend('native',{createGain:() => ({gain:{value:1},connect(){},disconnect(){}})},async () => voice)
	const settings = {reverbMode:'off'}
	await backend.configure(settings)
	const handle = {options:{},program:0}
	await backend.attach(handle)
	expect(soundfont.setEngineReverb).toHaveBeenLastCalledWith({reverbMode:'off'})
	handle.program = 48
	await backend.program(handle)
	expect(soundfont.setEngineReverb).toHaveBeenCalledTimes(2)
})
